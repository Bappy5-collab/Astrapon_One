/**
 * The spoken summary of a stored run: a few short lines a farmer can follow by ear. Which crops the
 * option ranked first grows, what to do if they choose it (planting and harvest dates), how much
 * water it needs, and what the dry season means for water. Each line is tied to the part of the
 * result page it describes, so the page can scroll to and highlight that part while it is read.
 *
 * Pure and deterministic: built only from the stored comparison, the dry-season outlook computed
 * from the field's stored NASA POWER series, and the app's own translated sentences. Nothing is
 * generated by a language model, so the voice can never say something the data does not hold.
 */

import type { RunView } from "./engine";
import { glance } from "./glance";
import { optionsOf } from "./view";

/** Page targets a line can point at (element ids on the run page). */
export type VoiceTarget = "voice-top" | `voice-tile-${string}` | "voice-water" | "voice-check";
export type VoiceSection = "crops" | "todo" | "water" | "dry" | "check";
export type VoiceLine = { section: VoiceSection; target: VoiceTarget; text: string };

/** Dry-season facts for the field (from drySeasonOutlook) and the top option's water need then. */
export type VoiceDrySeason = {
  noDrySeason: boolean;
  /** Dry calendar months (1–12) in season order. */
  dryMonths: number[];
  lowestMonth: number | null;
  /** Irrigation the option ranked first needs in the dry months on this field (m³ a year), if known. */
  dryNeedM3: number | null;
};

type Fmt = {
  digits: (s: string) => string;
  int: (v: number) => string;
  pct: (v: number | null | undefined) => string;
  monthName: (m: number) => string;
  dayMonth: (md: string) => string;
};
type Ctx = {
  /** Translated sentence for a key (unknown keys return null). */
  t: (key: string) => string | null;
  f: Fmt;
  fill: (template: string, vars: Record<string, string | number>) => string;
  /** Null when the field has no usable weather record for a dry-season outlook. */
  dry: VoiceDrySeason | null;
  /** How the comparison treated water: rain only, or fully irrigated (irrigation need computed). */
  irrigationMode: "rainfed" | "full";
};

export function voiceScript(run: RunView | undefined, ctx: Ctx): VoiceLine[] {
  if (!run?.comparison || !run.indicatorDefinitions) return [];
  const options = optionsOf(run);
  const top = options.find((o) => o.id === run.comparison!.ranking[0]);
  if (!top) return [];
  const tr = (k: string) => ctx.t(k) ?? "";
  const lines: VoiceLine[] = [];
  const say = (section: VoiceSection, target: VoiceTarget, ...parts: string[]) => {
    const text = parts.filter(Boolean).join(" ").replace(/\s+/g, " ").trim();
    if (text) lines.push({ section, target, text });
  };
  const list = (xs: string[]) => (xs.length < 2 ? (xs[0] ?? "") : `${xs.slice(0, -1).join(", ")} ${tr("voice.and")} ${xs.at(-1)}`);
  const mm = (v: number) => ctx.fill(tr("voice.mm"), { v: ctx.f.int(v) });

  // 1. Which crops.
  const name = top.kind === "baseline" ? tr("sim.option.baseline") : ctx.fill(tr("sim.option.alt"), { n: ctx.f.digits(top.id.replace("alternative-", "")) });
  const crops = [...new Set(top.plantings.map((p) => p.crop))];
  say(
    "crops",
    "voice-top",
    ctx.fill(tr(top.kind === "baseline" ? "voice.introBaseline" : "voice.intro"), { name, crops: list(crops) }),
    run.comparison.stability === "fragile" ? tr("sim.ex.fragile") : "",
  );

  // 2. What to do if they choose it: each crop's planting and harvest dates, once per crop and date.
  const seen = new Set<string>();
  const steps = top.plantings
    .filter((p) => {
      const k = `${p.crop}|${p.start}|${p.end}`;
      if (seen.has(k)) return false;
      seen.add(k);
      return true;
    })
    .map((p) => ctx.fill(tr("voice.step"), { crop: p.crop, start: ctx.f.dayMonth(p.start), end: ctx.f.dayMonth(p.end) }));
  if (steps.length) say("todo", "voice-top", ctx.fill(tr("voice.todo"), { steps: steps.join("; ") }));

  // 3. Water: the first water tile of the at-a-glance view, against what is grown now.
  const g = glance(run);
  const hasBase = !!g?.baselineId && g.baselineId !== g.topId;
  const water = g?.tiles.find((x) => x.topic === "water");
  if (water) {
    const value = (v: number) => (water.unit === "ratio" ? ctx.f.pct(v) : mm(v));
    const key = water.key === "irrigation_requirement" ? "voice.waterIrr" : water.key === "relative_water_supply" ? "voice.waterRain" : "voice.waterBalance";
    say("water", `voice-tile-${water.key}`, ctx.fill(tr(key), { v: value(water.top) }), hasBase && water.now != null ? ctx.fill(tr("voice.now"), { v: value(water.now) }) : "");
  } else {
    // No water figure in this run: say why instead of staying silent about water.
    say("water", "voice-water", tr(ctx.irrigationMode === "rainfed" ? "voice.waterRainfed" : "voice.waterNone"));
  }

  // 4. Dry season: when it is dry here, when ponds may run low, the water needed then, a dry year.
  const dry = ctx.dry;
  const dryYear = g?.tiles.find((x) => x.topic === "dry_years" && x.unit === "mm/year");
  const dryParts: string[] = [];
  if (dry?.noDrySeason) dryParts.push(tr("voice.noDry"));
  else if (dry && dry.dryMonths.length) {
    const from = ctx.f.monthName(dry.dryMonths[0]!);
    const to = ctx.f.monthName(dry.dryMonths.at(-1)!);
    dryParts.push(ctx.fill(tr(dry.dryMonths.length === 1 ? "voice.dryOne" : "voice.dry"), { from, to }));
    if (dry.lowestMonth) dryParts.push(ctx.fill(tr("voice.dryLow"), { low: ctx.f.monthName(dry.lowestMonth) }));
    if (dry.dryNeedM3 === 0) dryParts.push(tr("voice.dryNoNeed"));
    else if (dry.dryNeedM3 != null) dryParts.push(ctx.fill(tr("voice.dryNeed"), { v: ctx.f.int(Math.max(10, Math.round(dry.dryNeedM3 / 10) * 10)) }));
  }
  if (dryYear && dryYear.top > 0) dryParts.push(ctx.fill(tr("voice.dryYear"), { v: mm(dryYear.top) }));
  // A backup is worth planning only when the option needs water in those months (or it is unknown).
  if (dry && !dry.noDrySeason && dry.dryMonths.length && dry.dryNeedM3 !== 0) dryParts.push(tr("voice.dryDo"));
  if (dryParts.length) say("dry", dry ? "voice-water" : `voice-tile-${dryYear!.key}`, ...dryParts);

  // 5. The caution, always last.
  say("check", "voice-check", tr("sim.sum.checkBody"));
  return lines;
}
